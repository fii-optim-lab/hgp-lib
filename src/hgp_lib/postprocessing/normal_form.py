"""
Disjunctive and conjunctive normal forms.

`canonical` computes the canonical DNF or CNF of a tree. A term (a conjunction) is
stored as a cube: a dict from column index to the mask of cells it allows, without the
unconstrained columns. The canonical DNF is made of prime terms (terms that no longer
imply the rule once one more cell is allowed), keeping only those that are needed:

1. The tree is expanded into terms, dropping empty and absorbed terms as it goes.
2. All prime terms are generated by repeated consensus: two terms that differ on one
   column give the term that allows the cells of both on that column and the cells
   common to both elsewhere.
3. The primes are tried from the least to the most preferred (more conditions, then
   fewer allowed cells, then column and cell order), and removed while the others still
   cover them.

The set of primes depends only on what the tree computes, and the selection only on
the primes, so equivalent trees get the same normal form. The CNF is the negation of
the canonical DNF of the negated tree.

`mechanical` converts a rule without using the columns: negations are pushed down,
operators flattened, and ``And`` distributed over ``Or`` (DNF) or ``Or`` over ``And``
(CNF). Nothing is removed.
"""

from itertools import product

from ..rules import And, Literal, Or, Rule
from .domain import AND, OR, Domain
from .tree import FALSE, TRUE, Cond, Const, Node, make_op, negation

DNF = "dnf"
CNF = "cnf"


def canonical(node: Node, domain: Domain, form: str) -> Node:
    """
    The canonical DNF (``form == "dnf"``) or CNF (``form == "cnf"``) of ``node``.

    Returns:
        Node: An ``Or`` of ``And`` terms (DNF) or an ``And`` of ``Or`` clauses (CNF).
            A term or clause with one condition is the condition itself, a normal form
            with one term or clause is that term or clause, and a constant is `TRUE` or
            `FALSE`.
    """
    if form == DNF:
        cubes = _select(_primes(_expand(node, domain), domain), domain)
        terms = [_cube_node(cube, AND, domain, negate=False) for cube in cubes]
        return make_op(OR, terms)
    cubes = _select(_primes(_expand(negation(node, domain), domain), domain), domain)
    clauses = [_cube_node(cube, OR, domain, negate=True) for cube in cubes]
    return make_op(AND, clauses)


def _cube_node(cube: dict, operator: str, domain: Domain, negate: bool) -> Node:
    conditions = []
    for column in sorted(cube):
        mask = cube[column]
        if negate:
            mask = domain.columns[column].full & ~mask
        conditions.append(Cond(column, mask))
    if not conditions:
        return FALSE if negate else TRUE
    return make_op(operator, conditions)


# ---------------------------------------------------------------------------
# Cubes
# ---------------------------------------------------------------------------


def _full(domain: Domain, column: int) -> int:
    return domain.columns[column].full


def _intersect(a: dict, b: dict) -> dict | None:
    """The cube of the cells allowed by both, or ``None`` when there is none."""
    result = dict(a)
    for column, mask in b.items():
        if column in result:
            mask &= result[column]
            if mask == 0:
                return None
        result[column] = mask
    return result


def _contains(outer: dict, inner: dict) -> bool:
    """Whether every cell combination ``inner`` allows is allowed by ``outer``."""
    for column, mask in outer.items():
        if column not in inner or inner[column] & ~mask:
            return False
    return True


def _excluded(cube: dict, domain: Domain) -> int:
    return sum(
        (_full(domain, column) & ~mask).bit_count() for column, mask in cube.items()
    )


def _preference(cube: dict, domain: Domain) -> tuple:
    """Sort key: fewer conditions first, then fewer excluded cells, then by columns."""
    return len(cube), _excluded(cube, domain), sorted(cube.items())


def _absorb(cubes: list, domain: Domain) -> list:
    """Remove duplicates and cubes contained in another cube."""
    # A cube can only be contained in a cube with fewer or as many conditions, and with
    # fewer or as many excluded cells, so those come first.
    ordered = sorted(cubes, key=lambda cube: (len(cube), _excluded(cube, domain)))
    kept: list = []
    for cube in ordered:
        if not any(_contains(other, cube) for other in kept):
            kept.append(cube)
    return kept


def _expand(node: Node, domain: Domain) -> list:
    """The terms of a DNF of ``node``."""
    if isinstance(node, Const):
        return [{}] if node.value else []
    if isinstance(node, Cond):
        return [{node.column: node.mask}]
    parts = [_expand(child, domain) for child in node.children]
    if node.operator == OR:
        return _absorb([cube for part in parts for cube in part], domain)
    result = [{}]
    for part in sorted(parts, key=len):
        cubes = [_intersect(a, b) for a in result for b in part]
        result = _absorb([cube for cube in cubes if cube is not None], domain)
        if not result:
            break
    return result


# ---------------------------------------------------------------------------
# Prime terms and their selection
# ---------------------------------------------------------------------------


def _consensus(a: dict, b: dict, domain: Domain):
    """The consensus terms of ``a`` and ``b`` that are contained in neither."""
    for column in a.keys() & b.keys():
        mask_a, mask_b = a[column], b[column]
        if not mask_a & ~mask_b or not mask_b & ~mask_a:
            continue  # The consensus would be contained in a or b.
        cube = {}
        for other in a.keys() | b.keys():
            if other == column:
                continue
            mask = a.get(other, -1) & b.get(other, -1)
            if mask == 0:
                break
            cube[other] = mask
        else:
            union = mask_a | mask_b
            if union != _full(domain, column):
                cube[column] = union
            yield cube


def _key(cube: dict) -> tuple:
    return tuple(sorted(cube.items()))


def _primes(cubes: list, domain: Domain) -> list:
    """All prime terms of the DNF ``cubes``, by iterated consensus."""
    current = {_key(cube): cube for cube in _absorb(cubes, domain)}
    pending = list(current)
    while pending:
        key = pending.pop()
        cube = current.get(key)
        if cube is None:
            continue  # Absorbed since it was queued.
        for other in list(current.values()):
            for new in _consensus(cube, other, domain):
                if any(_contains(c, new) for c in current.values()):
                    continue
                current = {k: c for k, c in current.items() if not _contains(new, c)}
                new_key = _key(new)
                current[new_key] = new
                pending.append(new_key)
            if key not in current:
                break
    return list(current.values())


def _select(primes: list, domain: Domain) -> list:
    """
    Remove primes covered by the others, from the least to the most preferred, and
    return the rest in order of preference.
    """
    ordered = sorted(primes, key=lambda cube: _preference(cube, domain))
    kept = list(ordered)
    for cube in reversed(ordered):
        others = [c for c in kept if c is not cube]
        if _covers(others, cube, domain):
            kept = others
    return kept


def _covers(cubes: list, region: dict, domain: Domain) -> bool:
    """Whether the union of ``cubes`` contains ``region``."""
    inside = [c for c in (_intersect(cube, region) for cube in cubes) if c is not None]
    return _tautology(inside, region, domain)


def _tautology(cubes: list, region: dict, domain: Domain) -> bool:
    """Whether ``cubes``, all inside ``region``, cover it."""
    if not cubes:
        return False
    column = None
    for cube in cubes:
        if _contains(cube, region):
            return True
        if column is None:
            column = next(
                (c for c, m in cube.items() if m != region.get(c, _full(domain, c))),
                None,
            )
    # Split the region on ``column`` into groups of cells that the same cubes allow.
    full = _full(domain, column)
    groups: dict = {}
    for cell in domain.columns[column].cells(region.get(column, full)):
        bit = 1 << cell
        signature = tuple(bool(cube.get(column, full) & bit) for cube in cubes)
        groups[signature] = groups.get(signature, 0) | bit
    for signature, cells in groups.items():
        sub_region = dict(region)
        sub_region[column] = cells
        sub_cubes = []
        for cube, allowed in zip(cubes, signature):
            if allowed:
                sub_cube = dict(cube)
                sub_cube[column] = cells
                sub_cubes.append(sub_cube)
        if not _tautology(sub_cubes, sub_region, domain):
            return False
    return True


# ---------------------------------------------------------------------------
# Mechanical conversion
# ---------------------------------------------------------------------------


def mechanical(rule: Rule, form: str) -> Rule:
    """
    Convert ``rule`` to DNF or CNF by pushing negations down, flattening operators and
    distributing, without removing anything.
    """
    # A DNF is a list of terms, a CNF a list of clauses; both are lists of literals.
    outer, inner = (Or, And) if form == DNF else (And, Or)
    groups = _distribute(rule, outer is Or, False)
    parts = [
        inner(subrules=group, copy_subrules=False) if len(group) > 1 else group[0]
        for group in groups
    ]
    if len(parts) == 1:
        return parts[0]
    return outer(subrules=parts, copy_subrules=False)


def _distribute(rule: Rule, dnf: bool, negate: bool) -> list[list[Literal]]:
    negated = rule.negated != negate
    if isinstance(rule, Literal):
        return [[Literal(value=rule.value, negated=negated)]]
    is_and = isinstance(rule, And) != negated
    parts = [_distribute(child, dnf, negated) for child in rule.subrules]
    if is_and != dnf:
        # The outer operator of the normal form: concatenate the groups.
        return [group for part in parts for group in part]
    # The inner operator: one group per choice of a group in each part.
    return [
        [literal.copy(None) for group in choice for literal in group]
        for choice in product(*parts)
    ]


